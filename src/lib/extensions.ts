export { CURATED_FEATURED_IDS } from './featured-extensions';

const REPO = 'ganeshmshetty/openclip-extensions';
const BRANCH = 'main';
const CATALOG_URL = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/published/catalog.json`;
const STATS_URL = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/published/extension-stats.json`;
const FEATURED_URL = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/published/featured.json`;

// Featured IDs change rarely; cache a bit longer than the catalog.
const FEATURED_TTL_MS = 5 * 60 * 1000;
let cachedFeatured: string[] | null = null;
let cachedFeaturedAt = 0;

export async function loadFeatured(): Promise<string[]> {
  const now = Date.now();
  if (cachedFeatured && now - cachedFeaturedAt < FEATURED_TTL_MS) {
    return cachedFeatured;
  }
  try {
    const res = await fetch(FEATURED_URL, {
      headers: githubHeaders(),
    });
    if (!res.ok) {
      console.warn('Featured fetch failed:', res.status);
      return cachedFeatured ?? CURATED_FEATURED_IDS;
    }
    const data: unknown = await res.json();
    const ids = Array.isArray(data)
      ? data
          .filter((id): id is string => typeof id === 'string' && id.trim() !== '')
          .map((id) => id.trim())
      : [];
    if (ids.length === 0) {
      return cachedFeatured ?? CURATED_FEATURED_IDS;
    }
    cachedFeatured = ids;
    cachedFeaturedAt = Date.now();
    return cachedFeatured;
  } catch (err) {
    console.error('Failed to load featured:', err);
    return cachedFeatured ?? CURATED_FEATURED_IDS;
  }
}

// Optional GitHub token (set as GH_TOKEN or GITHUB_TOKEN in the Vercel
// environment) to raise api.github.com rate limits if raw.githubusercontent
// ever throttles us.
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || process.env.GH_TOKEN || '';

function githubHeaders(): HeadersInit {
  return GITHUB_TOKEN ? { Authorization: `Bearer ${GITHUB_TOKEN}` } : {};
}

// Download counts are published nightly to published/extension-stats.json by the
// update-stats.yml workflow (Obsidian model). Serve from a short cache to
// avoid re-fetching on every request; stats only change once a day.
const STATS_TTL_MS = 2 * 60 * 1000;
let cachedStats: Record<string, number> | null = null;
let cachedStatsAt = 0;
const CATALOG_TTL_MS = 60 * 1000;
let cachedCatalog: ExtensionItem[] | null = null;
let cachedCatalogAt = 0;

async function loadStats(): Promise<Record<string, number> | null> {
  const now = Date.now();
  if (cachedStats && now - cachedStatsAt < STATS_TTL_MS) {
    return cachedStats;
  }
  try {
    const res = await fetch(STATS_URL, {
      headers: githubHeaders(),
    });
    if (!res.ok) return cachedStats;
    const data = (await res.json()) as { downloads?: Record<string, number> };
    cachedStats = data.downloads ?? {};
    cachedStatsAt = Date.now();
    return cachedStats;
  } catch {
    return cachedStats;
  }
}

export async function getCatalog(): Promise<ExtensionItem[]> {
  const now = Date.now();
  if (cachedCatalog && now - cachedCatalogAt < CATALOG_TTL_MS) {
    return cachedCatalog;
  }

  try {
    const res = await fetch(CATALOG_URL, {
      headers: githubHeaders(),
    });
    if (!res.ok) {
      console.warn('Catalog fetch failed:', res.status);
      return cachedCatalog ?? [];
    }

    const data = (await res.json()) as {
      extensions?: ExtensionItem[];
    };

    // Merge GitHub Release download counts and synced README/manifest metadata.
    const stats = await loadStats();
    const syncedMap = (extensionsPayload?.extensions || {}) as unknown as Record<string, SyncedExtensionData>;
    const merged = (data.extensions ?? []).map((item) => {
      const lowerId = item.id.toLowerCase();
      const statsCount =
        stats?.[item.id] ??
        stats?.[lowerId] ??
        0;
      const catalogCount = item.downloadCount ?? 0;
      const synced = syncedMap[lowerId] || syncedMap[item.id] || {};
      return {
        ...item,
        downloadCount: Math.max(statsCount, catalogCount),
        actionType: synced.actionType || item.actionType,
        minOpenClipVersion: synced.minOpenClipVersion || item.minOpenClipVersion,
        sourceURL: synced.sourceURL || item.sourceURL,
        hasAuthoredReadme: synced.hasAuthoredReadme,
        readmeMarkdown: synced.readmeMarkdown || item.readmeMarkdown,
        options: synced.options || item.options,
        requirements: synced.requirements || item.requirements,
        keywords: synced.keywords || item.keywords,
        subActions: synced.subActions || item.subActions,
        iconURL: localIconURL(item.id),
      };
    });

    if (stats === null) {
      // Stats are unavailable. Prefer the last valid snapshot so counts don't blink
      // to zero; if there is none, serve the fresh catalog zeroed so the store never
      // renders empty. Either way, don't cache zeroed counts here — the next request
      // retries stats.
      console.warn('Stats unavailable; serving catalog without counts');
      return cachedCatalog ?? merged;
    }

    cachedCatalog = merged;
    cachedCatalogAt = Date.now();
    return merged;
  } catch (err) {
    console.error('Failed to load catalog:', err);
    return cachedCatalog ?? [];
  }
}

function resolveText(val: unknown): string {
  if (!val) return '';
  if (typeof val === 'string') return val.trim();
  if (typeof val === 'object' && val !== null) {
    const obj = val as Record<string, unknown>;
    if (typeof obj.en === 'string' && obj.en.trim()) return obj.en.trim();
    for (const k of Object.keys(obj)) {
      if (typeof obj[k] === 'string' && (obj[k] as string).trim()) return (obj[k] as string).trim();
    }
  }
  return '';
}

function determineActionType(manifest: any): string {
  const action = manifest?.action;
  const actions = manifest?.actions;

  if (action?.type) {
    switch (String(action.type).toLowerCase()) {
      case 'javascript':
        return 'JavaScript';
      case 'shell':
        return 'Shell Script';
      case 'applescript':
        return 'AppleScript';
      case 'url':
        return 'URL Template';
      case 'keypress':
        return 'Keypress Simulation';
      case 'shortcut':
        return 'macOS Shortcut';
      case 'group':
        return 'Action Group';
      case 'service':
        return 'macOS Service';
      default:
        return String(action.type).charAt(0).toUpperCase() + String(action.type).slice(1);
    }
  }

  if (action?.url) return 'URL Template';
  if (typeof action?.script === 'string') {
    if (action.script.endsWith('.js')) return 'JavaScript';
    if (action.script.endsWith('.sh') || action.script.endsWith('.zsh')) return 'Shell Script';
    if (action.script.endsWith('.applescript') || action.script.endsWith('.scpt')) return 'AppleScript';
    if (action.script.endsWith('.py')) return 'Python Script';
  }
  if (actions && Array.isArray(actions)) return 'Action Group';
  if (action?.keyCodes || action?.keyEquivalent) return 'Keypress Simulation';

  return 'Native Action';
}

function synthesizeReadme(data: {
  name: string;
  description: string;
  author: string;
  version: string;
  minOpenClipVersion?: string;
  actionType?: string;
  options?: ExtensionOption[];
  requirements?: ExtensionRequirements;
  subActions?: ExtensionSubAction[];
  keywords?: string[];
}): string {
  const lines: string[] = [];

  // Title and Description
  lines.push(`# ${data.name}`);
  lines.push('');
  if (data.description) {
    lines.push(data.description);
    lines.push('');
  }

  // Overview
  lines.push('## Overview');
  lines.push('');
  if (data.actionType) lines.push(`- **Action Engine**: ${data.actionType}`);
  lines.push(`- **Author**: ${data.author}`);
  lines.push(`- **Version**: v${data.version}`);
  lines.push(`- **Minimum OpenClip Version**: v${data.minOpenClipVersion || '1.0.0'}`);
  lines.push('- **Platform Compatibility**: macOS 14+ (Sonoma & Sequoia)');
  lines.push('');

  // Sub-Actions (if Action Group)
  if (data.subActions && data.subActions.length > 0) {
    lines.push('## Included Sub-Actions');
    lines.push('');
    lines.push('This action group includes multiple quick tools you can invoke individually:');
    lines.push('');
    for (const sub of data.subActions) {
      const typeLabel = sub.type ? ` (${sub.type})` : '';
      lines.push(`- **${sub.title}**${typeLabel}`);
    }
    lines.push('');
  }

  // Configuration Options
  if (data.options && data.options.length > 0) {
    lines.push('## Configuration Options');
    lines.push('');
    lines.push('You can customize this extension in OpenClip Settings (⌘,) › Extensions:');
    lines.push('');
    lines.push('| Setting | Key | Type | Default | Choices / Details |');
    lines.push('| :--- | :--- | :--- | :--- | :--- |');

    for (const opt of data.options) {
      const label = opt.label || opt.identifier;
      const key = `\`${opt.identifier}\``;
      const optType = opt.type || 'string';
      const defaultVal = opt.default !== undefined ? `\`${String(opt.default)}\`` : '*(none)*';
      let details = opt.description || '';
      if (opt.values && Array.isArray(opt.values) && opt.values.length > 0) {
        if (opt.values.length <= 6) {
          details = opt.values.map((v) => `\`${v}\``).join(', ');
        } else {
          details = `${opt.values.slice(0, 5).map((v) => `\`${v}\``).join(', ')} (+${opt.values.length - 5} more)`;
        }
      }
      lines.push(`| **${label}** | ${key} | ${optType} | ${defaultVal} | ${details || '—'} |`);
    }
    lines.push('');
  }

  // Trigger Requirements
  if (data.requirements) {
    const reqs: string[] = [];
    if (data.requirements.regex) {
      reqs.push(`- **Pattern Match**: Text must ${data.requirements.regexNegated ? 'not ' : ''}match regex: \`${data.requirements.regex}\``);
    }
    if (typeof data.requirements.minLength === 'number') {
      reqs.push(`- **Minimum Length**: ${data.requirements.minLength} characters`);
    }
    if (typeof data.requirements.maxLength === 'number') {
      reqs.push(`- **Maximum Length**: ${data.requirements.maxLength} characters`);
    }

    if (reqs.length > 0) {
      lines.push('## Activation Filters');
      lines.push('');
      lines.push('OpenClip only displays this action when the selected text satisfies these conditions:');
      lines.push('');
      lines.push(reqs.join('\n'));
      lines.push('');
    }
  }

  // How to Use
  lines.push('## How to Use');
  lines.push('');
  lines.push(`1. Select text in any macOS application (Safari, Notes, Messages, Terminal, Xcode, etc.).`);
  lines.push(`2. Click the **${data.name}** button in the floating OpenClip popup bar, or press your global command palette shortcut (\`⌥⌘C\`).`);
  lines.push(`3. OpenClip executes the action instantly in the background with zero background memory bloat.`);
  lines.push('');

  return lines.join('\n');
}

function extractPkgName(item: { downloadURL?: string; id: string }): string {
  if (item.downloadURL) {
    const match = item.downloadURL.match(/\/([^/]+)\.zip$/);
    if (match && match[1]) {
      return decodeURIComponent(match[1]);
    }
  }
  const suffix = item.id.split('.').pop() || item.id;
  return `${suffix}.openclipext`;
}

async function fetchRemoteReadme(pkgName: string): Promise<string | null> {
  const url = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/raw/${pkgName}/README.md`;
  try {
    const res = await fetch(url, {
      headers: githubHeaders(),
    });
    if (res.ok) {
      const text = await res.text();
      if (text.trim().length > 0) {
        return text.trim();
      }
    }
  } catch (err) {
    console.warn(`[Extensions] Failed to fetch remote README for ${pkgName}:`, err);
  }
  return null;
}

async function fetchRemoteManifest(pkgName: string): Promise<any | null> {
  const url = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/raw/${pkgName}/openclip.json`;
  try {
    const res = await fetch(url, {
      headers: githubHeaders(),
    });
    if (res.ok) {
      return await res.json();
    }
  } catch (err) {
    console.warn(`[Extensions] Failed to fetch remote manifest for ${pkgName}:`, err);
  }
  return null;
}

export async function getExtensionById(id: string): Promise<ExtensionItem | undefined> {
  const catalog = await getCatalog();
  const lowerId = id.toLowerCase();
  const found = catalog.find((ext) => ext.id.toLowerCase() === lowerId || ext.id === id);

  const syncedMap = (extensionsPayload?.extensions || {}) as unknown as Record<string, SyncedExtensionData>;
  const synced = syncedMap[lowerId] || syncedMap[id];

  let item: ExtensionItem | undefined;

  if (found) {
    if (synced) {
      item = {
        ...found,
        actionType: synced.actionType || found.actionType,
        minOpenClipVersion: synced.minOpenClipVersion || found.minOpenClipVersion,
        sourceURL: synced.sourceURL || found.sourceURL,
        hasAuthoredReadme: synced.hasAuthoredReadme,
        readmeMarkdown: synced.readmeMarkdown || found.readmeMarkdown,
        options: synced.options || found.options,
        requirements: synced.requirements || found.requirements,
        keywords: synced.keywords || found.keywords,
        subActions: synced.subActions || found.subActions,
      };
    } else {
      item = { ...found };
    }
  } else if (synced) {
    item = {
      id: synced.id,
      name: synced.name,
      description: synced.description,
      author: synced.author,
      icon: 'puzzlepiece',
      version: synced.version,
      downloadCount: 0,
      downloadURL: `https://github.com/${REPO}/releases/download/${encodeURIComponent(synced.id)}%40${synced.version}/${synced.pkgName}.zip`,
      iconURL: `https://cdn.jsdelivr.net/gh/${REPO}@main/published/icons/${synced.id}.svg`,
      actionType: synced.actionType,
      minOpenClipVersion: synced.minOpenClipVersion,
      sourceURL: synced.sourceURL,
      hasAuthoredReadme: synced.hasAuthoredReadme,
      readmeMarkdown: synced.readmeMarkdown,
      options: synced.options,
      requirements: synced.requirements,
      keywords: synced.keywords,
      subActions: synced.subActions,
    };
  }

  if (!item) return undefined;

  const pkgName = (synced && synced.pkgName) || extractPkgName(item);

  // If we don't have an authored readme yet, attempt to fetch live from GitHub
  if (!item.hasAuthoredReadme && pkgName) {
    const remoteReadme = await fetchRemoteReadme(pkgName);
    if (remoteReadme) {
      item.readmeMarkdown = remoteReadme;
      item.hasAuthoredReadme = true;
    }
  }

  // If this extension wasn't in the build-time syncedMap, fetch manifest to fill missing metadata
  if (!synced && pkgName) {
    const manifest = await fetchRemoteManifest(pkgName);
    if (manifest) {
      if (!item.actionType) item.actionType = determineActionType(manifest);
      if (!item.minOpenClipVersion) item.minOpenClipVersion = manifest.minOpenClipVersion || '1.0.0';
      if (!item.sourceURL) item.sourceURL = `https://github.com/${REPO}/tree/${BRANCH}/raw/${pkgName}`;
      if (!item.options && Array.isArray(manifest.options)) {
        item.options = manifest.options.map((o: any) => ({
          identifier: o.identifier,
          label: resolveText(o.label) || o.identifier,
          type: o.type || 'string',
          default: o.default,
          values: Array.isArray(o.values) ? o.values : undefined,
          description: resolveText(o.description),
        }));
      }
      if (!item.requirements) {
        item.requirements = manifest.requirements || manifest.action?.requirements;
      }
      if (!item.keywords && Array.isArray(manifest.keywords)) {
        item.keywords = manifest.keywords;
      }
      if (!item.subActions) {
        const subActions: ExtensionSubAction[] = [];
        if (manifest.action?.type === 'group' && Array.isArray(manifest.action.subActions)) {
          for (const sa of manifest.action.subActions) {
            subActions.push({
              id: sa.id,
              title: resolveText(sa.title) || sa.id || 'Action',
              type: sa.type || 'shell',
              icon: sa.icon,
            });
          }
        } else if (Array.isArray(manifest.actions)) {
          for (const sa of manifest.actions) {
            subActions.push({
              id: sa.identifier || sa.id,
              title: resolveText(sa.title) || sa.identifier || 'Action',
              type: sa.type || 'action',
              icon: sa.icon,
            });
          }
        }
        if (subActions.length > 0) item.subActions = subActions;
      }
    }
  }

  // If still no readmeMarkdown (neither authored nor remote), synthesize one
  if (!item.readmeMarkdown) {
    item.readmeMarkdown = synthesizeReadme({
      name: item.name,
      description: item.description,
      author: item.author,
      version: item.version || '1.0.0',
      minOpenClipVersion: item.minOpenClipVersion,
      actionType: item.actionType,
      options: item.options,
      requirements: item.requirements,
      subActions: item.subActions,
      keywords: item.keywords,
    });
  }

  item.iconURL = localIconURL(item.id);

  return item;
}

/**
 * Icons ship with the site (see `copyPublishedIcons` in scripts/sync-extensions.ts)
 * so the store's images come from its own origin, cache and lazy-load like normal
 * images, and never depend on a third-party CDN being reachable from the browser.
 *
 * The live catalog can list extensions newer than the local extensions clone, which
 * have no static file yet — those fall back to the same-origin proxy route.
 */
function localIconURL(id: string): string {
  const key = id.toLowerCase();
  const hash = (iconHashes as Record<string, string>)[key];
  return hash ? `/icons/extensions/${key}.svg?v=${hash}` : `/api/v1/icon/${encodeURIComponent(key)}`;
}

/**
 * Ids present in the build-time snapshot, for prerendering the store's detail pages.
 * Reads the committed payload rather than the live catalog so `generateStaticParams`
 * needs no network access at build time.
 */
export function getSyncedExtensionIds(): string[] {
  const syncedMap = (extensionsPayload?.extensions || {}) as unknown as Record<string, SyncedExtensionData>;
  const ids = new Set<string>();
  for (const entry of Object.values(syncedMap)) {
    if (entry?.id) ids.add(entry.id);
  }
  return [...ids];
}
