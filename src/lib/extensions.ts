export interface ExtensionOption {
  identifier: string;
  label?: string;
  type?: string;
  default?: unknown;
  values?: string[];
  description?: string;
}

export interface ExtensionSubAction {
  id?: string;
  title: string;
  type: string;
  icon?: string;
}

export interface ExtensionRequirements {
  regex?: string;
  regexNegated?: boolean;
  minLength?: number;
  maxLength?: number;
}

export interface SyncedExtensionData {
  id: string;
  pkgName: string;
  name: string;
  description: string;
  author: string;
  version: string;
  minOpenClipVersion?: string;
  actionType: string;
  sourceURL: string;
  hasAuthoredReadme: boolean;
  readmeMarkdown: string;
  options?: ExtensionOption[];
  requirements?: ExtensionRequirements;
  keywords?: string[];
  subActions?: ExtensionSubAction[];
}

export interface ExtensionItem {
  id: string;
  name: string;
  description: string;
  author: string;
  icon: string;
  version?: string;
  downloadCount: number;
  downloadURL: string;
  /** Normalized web icon (PNG) generated by the extensions publish pipeline. */
  iconURL?: string;
  /** ISO 8601 publication or release timestamp from catalog.json. */
  publishedAt?: string;
  /**
   * ISO 8601 timestamp of when the extension first appeared, stable across releases (the pipeline
   * writes it from the package's first commit). Drives "New"; absent in older catalog snapshots.
   */
  addedAt?: string;
  // Synced metadata & documentation
  actionType?: string;
  minOpenClipVersion?: string;
  sourceURL?: string;
  hasAuthoredReadme?: boolean;
  readmeMarkdown?: string;
  options?: ExtensionOption[];
  requirements?: ExtensionRequirements;
  keywords?: string[];
  subActions?: ExtensionSubAction[];
}

