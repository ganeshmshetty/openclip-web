/**
 * Custom Worker entry that wraps the OpenNext handler.
 *
 * GET /api/v1/extensions is about two thirds of all Worker requests (the macOS app
 * polls it) and most of the Worker CPU. Its response only depends on the URL and the
 * catalog, and the catalog only changes with a rebuild, so:
 *
 * 1. Plain `?page=&limit=` requests for a prebuilt limit (12, 50, 500) are served from
 *    static JSON baked at build time (scripts/build-extensions-api.ts) through the
 *    ASSETS binding. Next.js never boots and nothing is fetched from GitHub.
 * 2. Anything else (search, filter/sort, other limits, a missing file) is answered
 *    from this data center's Cache API, and only a miss runs the Next.js route.
 *
 * Workers Cache (`cache.enabled` in wrangler.jsonc) sits in front of the Worker as
 * well. Everything else goes straight to OpenNext.
 */
// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler
import { default as openNext } from './.open-next/worker.js';

import {
  EXTENSIONS_CACHE_HEADERS,
  OUT_OF_RANGE_PAGE_MARKER,
  PREBUILT_LIMITS,
  parsePagination,
  prebuiltOutOfRangePath,
  prebuiltPagePath,
} from './src/lib/extensions-query';

// @ts-expect-error: generated by `opennextjs-cloudflare build`, resolved by wrangler
export { DOQueueHandler, DOShardedTagCache, BucketCachePurge } from './.open-next/worker.js';

const CACHED_API_PATH = '/api/v1/extensions';
// The Cache API key carries the Worker version (see cacheKeyFor), and every catalog
// or stats change ships as a new deploy, so an entry can never outlive its data.
const CACHE_SECONDS = 86400;

type Handler = {
  fetch(request: Request, env: unknown, ctx: ExecutionContext): Promise<Response>;
};

type AssetsEnv = {
  ASSETS?: { fetch(input: Request | string | URL): Promise<Response> };
  // `version_metadata` binding in wrangler.jsonc; absent in `next dev`.
  CF_VERSION_METADATA?: { id: string };
};

/**
 * Cache API entries are keyed on the URL alone and, unlike Workers Cache, survive a
 * deploy. Adding the Worker version id makes every deploy (including the catalog
 * deploy hook) start from an empty cache, so a long TTL can't hide new extensions.
 */
function cacheKeyFor(url: URL, env: AssetsEnv): Request {
  const key = new URL(url.toString());
  const version = env.CF_VERSION_METADATA?.id;
  if (version) key.searchParams.set('__v', version);
  return new Request(key.toString(), { method: 'GET' });
}

// What the route's response carries via next.config.ts headers() plus the route
// itself. Asset responses never get next.config.ts headers, so set them here.
const STATIC_API_HEADERS: Record<string, string> = {
  'Content-Type': 'application/json',
  ...EXTENSIONS_CACHE_HEADERS,
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, OPTIONS',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=()',
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
};

const PREBUILT = new Set<number>(PREBUILT_LIMITS);

function jsonResponse(body: BodyInit | null): Response {
  const res = new Response(body, { status: 200, headers: STATIC_API_HEADERS });
  res.headers.set('X-OpenClip-Cache', 'STATIC');
  return res;
}

/**
 * The prebuilt answer for a plain `?page=&limit=` request, or null to fall through.
 * Uses the route's own page/limit normalization, so `limit=abc` (→ 12) or `page=0`
 * (→ 1) map to the same file the route would compute.
 */
async function servePrebuilt(url: URL, env: AssetsEnv): Promise<Response | null> {
  if (!env.ASSETS) return null;
  const keys = [...url.searchParams.keys()];
  if (keys.some((k) => k !== 'page' && k !== 'limit') || new Set(keys).size !== keys.length) {
    return null;
  }
  const { page, limit } = parsePagination(url.searchParams);
  if (!PREBUILT.has(limit)) return null;

  const asset = await env.ASSETS.fetch(new URL(prebuiltPagePath(limit, page), url.origin));
  if (asset.ok) return jsonResponse(asset.body);
  if (asset.status !== 404 || page === 1) return null;

  // Past the last page: the route returns an empty `extensions` list with the
  // requested page number, so fill that into the prebuilt template.
  const tail = await env.ASSETS.fetch(new URL(prebuiltOutOfRangePath(limit), url.origin));
  if (!tail.ok) return null;
  const text = await tail.text();
  const at = text.lastIndexOf(OUT_OF_RANGE_PAGE_MARKER);
  if (at === -1) return null;
  return jsonResponse(
    `${text.slice(0, at)},"page":${page},"totalPages":${text.slice(at + OUT_OF_RANGE_PAGE_MARKER.length)}`
  );
}

const next = openNext as Handler;

const worker = {
  async fetch(request: Request, env: unknown, ctx: ExecutionContext): Promise<Response> {
    const url = new URL(request.url);
    if (
      request.method !== 'GET' ||
      url.pathname !== CACHED_API_PATH ||
      request.headers.has('authorization')
    ) {
      return next.fetch(request, env, ctx);
    }

    const prebuilt = await servePrebuilt(url, env as AssetsEnv);
    if (prebuilt) return prebuilt;

    // Key on the full URL (path + query) plus the deploy, so request headers never
    // split the cache and a deploy never serves the previous catalog.
    const cacheKey = cacheKeyFor(url, env as AssetsEnv);
    const cache = (caches as unknown as { default: Cache }).default;

    const hit = await cache.match(cacheKey);
    if (hit) {
      const res = new Response(hit.body, hit);
      res.headers.set('X-OpenClip-Cache', 'HIT');
      return res;
    }

    const fresh = await next.fetch(request, env, ctx);
    // Only share real answers: the route marks a GitHub fallback `no-store`.
    if (fresh.status !== 200 || /no-store/i.test(fresh.headers.get('Cache-Control') ?? '')) {
      return fresh;
    }

    const res = new Response(fresh.body, fresh);
    res.headers.set('X-OpenClip-Cache', 'MISS');
    const stored = res.clone();
    stored.headers.set('Cache-Control', `public, max-age=${CACHE_SECONDS}`);
    stored.headers.delete('Set-Cookie');
    ctx.waitUntil(cache.put(cacheKey, stored));
    return res;
  },
};

export default worker;
