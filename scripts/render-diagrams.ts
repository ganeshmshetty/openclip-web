/**
 * Renders every ```mermaid fence in the docs to an inline SVG using pele.
 *
 * Mermaid is ~800 KB of JavaScript, and Turbopack hoists a dynamically imported
 * chunk into a page's initial script list — so a lazy `import()` still shipped it
 * to every doc page. Pele replaces it at build time: ~5 ms per diagram, a fraction
 * of the output size, and no diagram library in the browser bundle.
 *
 * Output is `src/docs/diagrams.generated.ts`, a hash → SVG map that
 * `DiagramImage` inlines. Inlining (rather than `<img src>`) is what lets pele's
 * CSS variables pick up the page theme, so one SVG serves light and dark.
 *
 *   bun run scripts/render-diagrams.ts
 */
import { existsSync, readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';
import { render } from 'pele';
import { diagramHash, DIAGRAM_LANGUAGE } from '../src/docs/diagram-hash';

interface DocRecord {
  rawMarkdown?: string;
}

function collectDiagrams(): Map<string, string> {
  const dataFile = resolve(__dirname, '../src/docs/data/docsData.json');
  if (!existsSync(dataFile)) {
    throw new Error(`Missing ${dataFile}. Run \`bun run scripts/sync-docs.ts\` first.`);
  }

  const parsed = JSON.parse(readFileSync(dataFile, 'utf-8')) as { allDocs?: DocRecord[] };
  const fence = new RegExp('```' + DIAGRAM_LANGUAGE + '\\n([\\s\\S]*?)```', 'g');

  const charts = new Map<string, string>();
  for (const doc of parsed.allDocs ?? []) {
    if (!doc.rawMarkdown) continue;
    for (const match of doc.rawMarkdown.matchAll(fence)) {
      const chart = match[1].trim();
      if (chart) charts.set(diagramHash(chart), chart);
    }
  }
  return charts;
}

function main() {
  const charts = collectDiagrams();
  const rendered: Array<[string, string]> = [];
  const failures: string[] = [];

  for (const [hash, chart] of charts) {
    try {
      const { svg } = render(chart, { idPrefix: `pele-${hash}`, responsive: true });
      if (!svg.trim().startsWith('<svg')) throw new Error('pele did not return an SVG');
      rendered.push([hash, svg]);
    } catch (err) {
      failures.push(`${hash}: ${err instanceof Error ? err.message : String(err)}`);
    }
  }

  const banner = `// Generated by scripts/render-diagrams.ts — do not edit by hand.
// Regenerate with: bun run scripts/render-diagrams.ts
`;
  const body = `export const DIAGRAM_SVGS: Record<string, string> = ${JSON.stringify(
    Object.fromEntries(rendered),
    null,
    2
  )};
`;
  const outFile = resolve(__dirname, '../src/docs/diagrams.generated.ts');
  writeFileSync(outFile, banner + body, 'utf-8');

  const bytes = rendered.reduce((sum, [, svg]) => sum + svg.length, 0);
  console.log(
    `[Diagrams] ✓ Rendered ${rendered.length}/${charts.size} diagram(s) with pele ` +
      `(${Math.round(bytes / 1024)} KB) → src/docs/diagrams.generated.ts`
  );

  if (failures.length > 0) {
    // Surfaced rather than thrown: a diagram that pele cannot parse falls back to
    // a code block at render time, which is better than failing the whole build.
    console.warn(`[Diagrams] ⚠ ${failures.length} diagram(s) failed to render:`);
    for (const failure of failures) console.warn(`           ${failure}`);
  }
}

main();
